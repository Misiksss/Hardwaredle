        /* --- Dashboard & Balanced Macro Calculations --- */
        function calculateGoals(e) {
            e.preventDefault();
            const gender = document.getElementById('calc-gender').value;
            const age = parseFloat(document.getElementById('calc-age').value);
            const weight = parseFloat(document.getElementById('calc-weight').value);
            const height = parseFloat(document.getElementById('calc-height').value);
            const activity = parseFloat(document.getElementById('calc-activity').value);

            let bmr = (10 * weight) + (6.25 * height) - (5 * age);
            bmr = gender === 'male' ? bmr + 5 : bmr - 161;
            
            const tdee = Math.round(bmr * activity);
            
            // Balanced Macro Split: ~30% Protein, ~30% Fat, ~40% Carbs
            const proteinGrams = Math.round((tdee * 0.30) / 4);
            const fatGrams = Math.round((tdee * 0.30) / 9);
            const carbGrams = Math.round((tdee * 0.40) / 4);

            state.goals = { kcal: tdee, protein: proteinGrams, carbs: carbGrams, fat: fatGrams };
            saveState();
            updateDashboardUI();
            toggleElement('calc-form');
            
            const btn = document.getElementById('btn-calc-goals');
            const dict = translations[state.lang] || translations['en'];
            const originalText = dict.calcGoals;
            btn.textContent = dict.saved;
            btn.classList.add('bg-red-600');
            setTimeout(() => {
                btn.textContent = originalText;
                btn.classList.remove('bg-red-600');
            }, 1500);
        }

        function updateDashboardUI() {
            const dict = translations[state.lang] || translations['en'];
            const totalAllowance = state.goals.kcal + (state.burned || 0);
            const remKcal = Math.max(0, totalAllowance - state.consumed.kcal);
            
            document.getElementById('dash-cals-remaining').innerHTML = `${remKcal} <span class="text-lg font-medium text-slate-500">${dict.kcal}</span>`;
            document.getElementById('dash-cals-consumed').textContent = state.consumed.kcal;

            const updateBar = (macro) => {
                const goal = state.goals[macro] || 1;
                const cons = state.consumed[macro];
                const pct = Math.min(100, (cons / goal) * 100);
                
                document.getElementById(`text-prog-${macro}`).textContent = `${cons}g / ${goal}g`;
                document.getElementById(`bar-prog-${macro}`).style.width = `${pct}%`;
            };

            updateBar('protein');
            updateBar('carbs');
            updateBar('fat');
        }

